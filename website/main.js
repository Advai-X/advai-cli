const supportedLanguages = new Set(Object.keys(translations));
const languageButtons = document.querySelectorAll("[data-language]");
const toast = document.querySelector(".copy-toast");
let currentLanguage = "en";
let toastTimer;

function getInitialLanguage() {
  const queryLanguage = new URLSearchParams(window.location.search).get("lang");
  if (supportedLanguages.has(queryLanguage)) return queryLanguage;

  const storedLanguage = window.localStorage.getItem("advai-language");
  if (supportedLanguages.has(storedLanguage)) return storedLanguage;

  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

function setLanguage(language, updateUrl = true) {
  currentLanguage = supportedLanguages.has(language) ? language : "en";
  const messages = translations[currentLanguage];

  document.documentElement.lang = currentLanguage === "zh" ? "zh-CN" : "en";
  document.title = messages.pageTitle;
  document.querySelector('meta[name="description"]').setAttribute("content", messages.description);
  document.querySelector('meta[property="og:description"]').setAttribute("content", messages.description);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const message = messages[element.dataset.i18n];
    if (message !== undefined) element.innerHTML = message;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const message = messages[element.dataset.i18nAria];
    if (message !== undefined) element.setAttribute("aria-label", message);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const message = messages[element.dataset.i18nAlt];
    if (message !== undefined) element.setAttribute("alt", message);
  });

  languageButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.language === currentLanguage));
  });

  window.localStorage.setItem("advai-language", currentLanguage);

  if (updateUrl) {
    const url = new URL(window.location.href);
    url.searchParams.set("lang", currentLanguage);
    window.history.replaceState({}, "", url);
  }
}

function showToast(message) {
  window.clearTimeout(toastTimer);
  toast.textContent = message;
  toast.classList.add("visible");
  toastTimer = window.setTimeout(() => toast.classList.remove("visible"), 1800);
}

async function copyText(button) {
  const originalKey = button.dataset.i18n;

  try {
    await navigator.clipboard.writeText(button.dataset.copy);
    button.textContent = translations[currentLanguage].copied;
    showToast(translations[currentLanguage].copySuccess);
    window.setTimeout(() => {
      if (originalKey) button.textContent = translations[currentLanguage][originalKey];
    }, 1400);
  } catch {
    const textarea = document.createElement("textarea");
    textarea.value = button.dataset.copy;
    textarea.style.position = "fixed";
    textarea.style.opacity = "0";
    document.body.appendChild(textarea);
    textarea.select();
    document.execCommand("copy");
    textarea.remove();
    showToast(translations[currentLanguage].copySuccess);
  }
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

document.querySelectorAll("[data-copy]").forEach((button) => {
  button.addEventListener("click", () => copyText(button));
});

setLanguage(getInitialLanguage(), false);
